export async function buildProject(spec: Spec, caps: Capability[]): Promise<Record<string, string>> {
  const s = cleanSpec(spec);
  const files: Record<string, string> = {};
  for (const rel of await walk(TEMPLATE_DIR)) files[rel.split(path.sep).join("/")] = await readFile(path.join(TEMPLATE_DIR, rel), "utf8");
  const { referenceUrl: _r, referenceTitle: _t, ...config } = s;
  void _r; void _t;
  files["src/config.json"] = JSON.stringify(config, null, 2) + "\n";
  files["prisma/schema.prisma"] = schema(s);
  files["prisma/seed.mjs"] = seed(s);
  files[".env.example"] = envExample(s);
  files["README.md"] = readme(s, caps);
  files["public/icon.svg"] = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="${s.design.primary}"/><text x="32" y="42" font-family="Arial" font-size="30" font-weight="700" fill="#fff" text-anchor="middle">${s.name.replace(/^My\s+/i, "").charAt(0).toUpperCase().replace(/[<&>]/g, "")}</text></svg>`;
  files["package.json"] = JSON.stringify({
    name: s.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "platform", version: "0.1.0", private: true,
    scripts: { dev: "next dev", build: "next build", start: "next start", postinstall: "prisma generate", seed: "node prisma/seed.mjs", "db:push": "prisma db push" },
    dependencies: { "@prisma/client": "^6.19.0", bcryptjs: "^3.0.2", jose: "^6.1.0", next: "^16.0.0", react: "^19.2.0", "react-dom": "^19.2.0", "server-only": "^0.0.1", prisma: "^6.19.0" },
    devDependencies: { "@types/node": "^22", "@types/react": "^19", "@types/react-dom": "^19", typescript: "^5" },
  }, null, 2) + "\n";
  files["next-env.d.ts"] = `/// <reference types="next" />\n/// <reference types="next/image-types/global" />\n`;
  return files;
}
